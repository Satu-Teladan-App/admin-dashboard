import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const files = ['008_app_admin_chat.sql', '009_admin_content_operations.sql', '010_admin_role_operations.sql', '011_admin_action_guards.sql', '012_account_review.sql'];
const parts = [];
for (const file of files) {
  const source = await readFile(new URL('../supabase/migrations/' + file, import.meta.url), 'utf8');
  if (!source.startsWith('BEGIN;') || !source.trimEnd().endsWith('COMMIT;')) throw new Error('Expected transactional migration: ' + file);
  const hash = createHash('sha256').update(source).digest('hex');
  parts.push(`-- Source: ${file}\n-- SHA256: ${hash}\n${source.replace(/^BEGIN;\s*/, '').replace(/COMMIT;\s*$/, '')}`);
}
const target = new URL('../supabase/operations/app-admin-install.sql', import.meta.url);
await mkdir(new URL('../supabase/operations/', import.meta.url), { recursive: true });
await writeFile(target, `-- Generated by scripts/prepare-app-admin-migration.mjs. Run once, after backup and review.\n-- Applies only the app/admin package; migration 004 is deliberately excluded.\nBEGIN;\nSET LOCAL lock_timeout='10s';\nSET LOCAL statement_timeout='90s';\n\n${parts.join('\n')}\nCOMMIT;\n`);
console.log('Prepared one atomic SQL package: supabase/operations/app-admin-install.sql');
